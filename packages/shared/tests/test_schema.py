"""The schema enforces ORIGIN's integrity rules, not just the application code."""

from __future__ import annotations

import asyncio
from datetime import UTC, datetime

import pytest
from alembic import command
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError, IntegrityError
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession

from origin_core.db.migrate import alembic_config
from origin_core.db.models import (
    AuditEvent,
    Claim,
    Narrative,
    NarrativeClaim,
    ProviderQuota,
    Sighting,
    TimestampEvidence,
)
from origin_core.enums import Actor, BoundType, Confidence, EvidenceKind, QuotaPeriod

from .factories import make_graph

pytestmark = pytest.mark.db


def _claim(sighting: Sighting) -> Claim:
    return Claim(
        run_id=sighting.run_id,
        sighting_id=sighting.id,
        event="flood",
        quote="Flooding in the city centre",
        quote_start=0,
        quote_end=27,
        llm_provider="recorded",
        llm_model="none",
        prompt_version="claim.v1",
    )


async def test_models_match_migrations(db_engine: AsyncEngine, database_url: str) -> None:
    # Raises alembic.util.exc.AutogenerateDiffsDetected if the ORM and schema disagree.
    await asyncio.to_thread(command.check, alembic_config(database_url))


async def test_audit_events_are_append_only(db: AsyncSession) -> None:
    event = AuditEvent(actor=Actor.SYSTEM, action="test.created")
    db.add(event)
    await db.flush()

    with pytest.raises(DBAPIError, match="append-only"):
        async with db.begin_nested():
            await db.execute(
                text("UPDATE audit_events SET action = 'x' WHERE id = :id"), {"id": event.id}
            )
    with pytest.raises(DBAPIError, match="append-only"):
        async with db.begin_nested():
            await db.execute(text("DELETE FROM audit_events WHERE id = :id"), {"id": event.id})


async def test_claim_requires_existing_sighting(db: AsyncSession) -> None:
    graph = await make_graph(db)
    orphan = _claim(graph.sighting)
    orphan.sighting_id = graph.run.id  # a UUID that is not a sighting
    with pytest.raises(IntegrityError):
        async with db.begin_nested():
            db.add(orphan)
            await db.flush()


async def test_narrative_without_claim_is_rejected(db: AsyncSession) -> None:
    graph = await make_graph(db)
    with pytest.raises(DBAPIError, match="has no claims"):
        async with db.begin_nested():
            db.add(
                Narrative(
                    run_id=graph.run.id,
                    label="empty",
                    divergence_sighting_id=graph.sighting.id,
                    llm_provider="recorded",
                    llm_model="none",
                    prompt_version="narrative.v1",
                )
            )
            await db.flush()
            await db.execute(text("SET CONSTRAINTS ALL IMMEDIATE"))


async def test_narrative_with_claim_is_accepted(db: AsyncSession) -> None:
    graph = await make_graph(db)
    claim = _claim(graph.sighting)
    narrative = Narrative(
        run_id=graph.run.id,
        label="flood",
        divergence_sighting_id=graph.sighting.id,
        llm_provider="recorded",
        llm_model="none",
        prompt_version="narrative.v1",
    )
    db.add_all([claim, narrative])
    await db.flush()
    db.add(NarrativeClaim(narrative_id=narrative.id, claim_id=claim.id))
    await db.flush()
    await db.execute(text("SET CONSTRAINTS ALL IMMEDIATE"))

    # Removing the last claim would leave an empty narrative: rejected.
    with pytest.raises(DBAPIError, match="has no claims"):
        async with db.begin_nested():
            await db.execute(
                text("DELETE FROM narrative_claims WHERE narrative_id = :n"), {"n": narrative.id}
            )
            await db.execute(text("SET CONSTRAINTS ALL IMMEDIATE"))


async def test_quota_cannot_exceed_limit(db: AsyncSession) -> None:
    quota = ProviderQuota(
        provider="serpapi",
        period_kind=QuotaPeriod.MONTH,
        period_start=datetime(2026, 11, 1, tzinfo=UTC),
        limit_units=250,
        used_units=250,
    )
    db.add(quota)
    await db.flush()
    with pytest.raises(IntegrityError):
        async with db.begin_nested():
            await db.execute(
                text("UPDATE provider_quota SET used_units = used_units + 1 WHERE id = :id"),
                {"id": quota.id},
            )


async def test_sighting_date_interval_must_be_ordered(db: AsyncSession) -> None:
    graph = await make_graph(db)
    graph.sighting.date_lower = datetime(2024, 1, 2, tzinfo=UTC)
    graph.sighting.date_upper = datetime(2024, 1, 1, tzinfo=UTC)
    with pytest.raises(IntegrityError):
        async with db.begin_nested():
            await db.flush()


async def test_dating_vocabulary_includes_floors_and_observations(db: AsyncSession) -> None:
    graph = await make_graph(db)
    for kind, bound in (
        (EvidenceKind.OBSERVED, BoundType.NO_LATER_THAN),
        (EvidenceKind.EXIF, BoundType.NO_EARLIER_THAN),
    ):
        db.add(
            TimestampEvidence(
                sighting_id=graph.sighting.id,
                kind=kind,
                value=datetime(2024, 3, 1, tzinfo=UTC),
                bound=bound,
                confidence=Confidence.HIGH,
            )
        )
    await db.flush()
